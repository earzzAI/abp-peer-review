"""
Acoustic Behavioural Phenotyping (ABP) - Stage 4 Analytics Pipeline

This script executes Stage 4 (Operational Decision-Support Logic and Analytical Tiers) 
and evaluates the Proactive Evaluation Window (Δt) prior to physical collapse. 
It processes the raw daily decompensation probabilities (P_{i,t}) generated by the 
Stage 3 XGBoost classifier.
"""

import pandas as pd
import numpy as np

# ==========================================
# 1. LOGIC PARAMETERS (STAGE 4 THRESHOLDS)
# ==========================================
Z_RED_FLAG = 1.5      # Z_{E,t} = 1.5 threshold for Acute Departure (Red Flag Tier)
Z_ACCUMULATOR = 0.7   # Z_{E,t} = 0.7 threshold for Cumulative Drift (Accumulator Tier)
STATIC_FLOOR = 0.60   # Absolute safety override (P_{i,t} = 0.60)
PTS_THRESH = 10       # Behavioral accumulation points (A_{i,t} = 10 in trailing 3-day window)
GATING_WINDOW = 10    # Analytical refractory window (Days) suppressing duplicate signal activations
MIN_RECORDS = 14      # n_{14d} = 14 rule: 14/14 complete baseline nights required for Personalised Normalcy Profile (PNP)

max_window = 14       # 14-day maximum pre-fall lookback horizon for early-warning evaluation

# ==========================================
# 2. CORE LOGIC ENGINE (STAGE 4)
# ==========================================
def apply_decision_support(group):
    # Ensure date is a datetime object for rolling windows and temporal evaluations
    group['date'] = pd.to_datetime(group['date'])
    group = group.sort_values('date')
    
    # Pre-Analytical Quality Control: Calculate rolling 14-day data sufficiency 
    temp_idx = group.set_index('date')
    group['records_last_14d'] = temp_idx['prediction_prob'].rolling('14D').count().values
    
    # Calculate gap metrics for Cumulative Drift (Accumulator) continuity constraints
    gap_days = group['date'].diff().dt.days
    has_2d_gap = gap_days >= 3 # A difference of >= 3 days means 2 or more consecutive days missing
    span_3_records = group['date'].diff(periods=2).dt.days
    
    # Flag if the 3-day accumulation has insufficient sequence continuity
    acc_data_issue = (has_2d_gap.rolling(window=3, min_periods=1).max() == 1) | (span_3_records >= 5)

    # ---------------------------------------------------------
    # Digital Signal Filtering & Personalised Standardisation
    # ---------------------------------------------------------
    # E_{i,t}: Exponentially Weighted Moving Average (EWMA) smoothing, span = 2 days
    group['ewma'] = group['prediction_prob'].ewm(span=2, adjust=False).mean()
    
    # μ_{E,t}: 14-day rolling historical baseline mean
    group['mean'] = group['ewma'].shift(1).rolling(window=14, min_periods=7).mean()
    
    # σ_{E,t}: 14-day rolling standard deviation (clipped to lower bound 0.03)
    group['std'] = group['ewma'].shift(1).rolling(window=14, min_periods=7).std().clip(lower=0.03)
    
    # Z_{E,t}: Personalised Baseline Standardisation (Z-Score)
    group['z_score'] = (group['ewma'] - group['mean']) / group['std']
    
    # ---------------------------------------------------------
    # Observable Behavioural Symptom Gating (S_{trend}, S_{agitation}, S_{sleep})
    # ---------------------------------------------------------
    # S_{trend}: Monotonic trajectory escalation trend over trailing nights
    sym_trend = (group['ewma'] > group['ewma'].shift(1)) & (group['ewma'].shift(1) > group['ewma'].shift(2))
    
    # S_{agitation}: Current burstiness parameter strictly exceeds 14-day baseline mean
    sym_agitation = (group['burstiness_night_0'] > group['burstiness_night_0'].shift(1).rolling(14, 7).mean()).fillna(False)
    
    # S_{sleep}: Core Night (00:00–04:00) activity fraction strictly exceeds 14-day baseline mean
    sym_sleep = (group['fraction_core_night_0'] > group['fraction_core_night_0'].shift(1).rolling(14, 7).mean()).fillna(False)
    
    any_sym = (sym_trend | sym_agitation | sym_sleep)

    # ---------------------------------------------------------
    # Analytical Tiers (Decision-Support Logic)
    # ---------------------------------------------------------
    # Θ_{acute}: Acute Departure Threshold (Red Flag Tier)
    is_rf = ((group['z_score'] >= Z_RED_FLAG) & (sym_trend | sym_agitation)) | (group['prediction_prob'] >= STATIC_FLOOR)
    
    # Θ_{cumulative}: Cumulative Drift Threshold (Accumulator Tier)
    pts = np.where((group['z_score'] > Z_ACCUMULATOR) & any_sym, 10, 0)
    is_acc = pd.Series(pts, index=group.index).rolling(3, 1).sum() >= PTS_THRESH
    
    # Evaluate strict operational hierarchy and assign raw severity for refractory gating
    alert_labels = []
    raw_sevs = []
    for i in range(len(group)):
        rec_14d = group['records_last_14d'].iloc[i]
        rf = is_rf.iloc[i]
        acc_raw = is_acc.iloc[i]
        acc_issue = acc_data_issue.iloc[i]
        
        # Hierarchy: Insufficient baseline > Acute Departure (Red Flag) > Insufficient accumulator > Cumulative Drift > None
        if rec_14d < MIN_RECORDS:
            alert_labels.append("Insufficient baseline data")
            raw_sevs.append(0)
        elif rf:
            alert_labels.append("Red Flag") # Acute Departure
            raw_sevs.append(2)
        elif acc_raw and acc_issue:
            alert_labels.append("Insufficient accumulator data")
            raw_sevs.append(0)
        elif acc_raw and not acc_issue:
            alert_labels.append("Accumulator") # Cumulative Drift
            raw_sevs.append(1)
        else:
            alert_labels.append("None")
            raw_sevs.append(0)
            
    group['pre_gating_alert_type'] = alert_labels
    group['raw_sev'] = raw_sevs

    # Apply Operational Refractory Gating (10-Day Silence Window)
    notified, notified_sev = [], []
    last_date, last_sev = None, 0
    for _, row in group.iterrows():
        trigger, sev = 0, 0
        if row['raw_sev'] > 0:
            # Trigger if: No previous state transition OR refractory window expired OR severity escalated
            if last_date is None or (row['date'] - last_date).days > GATING_WINDOW or row['raw_sev'] > last_sev:
                trigger, sev = 1, row['raw_sev']
                last_date, last_sev = row['date'], sev
        notified.append(trigger)
        notified_sev.append(sev)
        
    group['notified'] = notified
    group['notified_severity'] = notified_sev
    
    # Assign final behavioural state transition label
    final_alert_types = []
    for i in range(len(group)):
        pre_label = group['pre_gating_alert_type'].iloc[i]
        n_sev = group['notified_severity'].iloc[i]
        
        if pre_label in ["Insufficient baseline data", "Insufficient accumulator data"]:
            final_alert_types.append(pre_label)
        elif n_sev == 2:
            final_alert_types.append("Red Flag") # Operational label for Acute Departure
        elif n_sev == 1:
            final_alert_types.append("Accumulator") # Operational label for Cumulative Drift
        else:
            final_alert_types.append("None")
            
    group['alert_type'] = final_alert_types
    
    return group

# ==========================================
# 3. EXECUTION AND DATA LOADING
# ==========================================

def execute_post_pred(df, eval_start):

    # Ensure proper date formatting
    df['date'] = pd.to_datetime(df['date']).dt.date

    # Run logic across all residents mapping multi-night trajectory drift
    processed = df.groupby('monitor_id', group_keys=True).apply(apply_decision_support, include_groups=False).reset_index(level=0)
    
    # Convert overall date back to datetime for performance reconciliation
    processed['date'] = pd.to_datetime(processed['date'])

    # Initialize new tracking columns for evaluation
    processed['lead_time'] = np.nan # Maps to Proactive Evaluation Window (Δt)
    processed['excluded_from_recall'] = False

    # ==========================================
    # 4. PERFORMANCE RECONCILIATION & EPIDEMIOLOGY
    # ==========================================
    
    # --- PROACTIVE EVALUATION WINDOW (Δt) & SENSITIVITY CALCULATION ---
    falls = processed[processed['Target'] == 1]
    caught_count = 0
    valid_fall_count = 0
    
    for idx, row in falls.iterrows():
        # Exclude fall from protocol-valid pool if 14/14 baseline data is insufficient
        if row['records_last_14d'] < MIN_RECORDS:
            processed.loc[idx, 'excluded_from_recall'] = True
            continue

        m_id, fd = row['monitor_id'], row['date']
        m_data = processed[processed['monitor_id'] == m_id]
        
        # Isolate the 14-day pre-fall lookback horizon
        window_alerts = m_data[(m_data['date'] >= fd - pd.Timedelta(days=max_window)) & 
                               (m_data['date'] <= fd)]
        
        valid_alerts = window_alerts[window_alerts['alert_type'].isin(['Red Flag', 'Accumulator'])]
        insufficient_acc_alerts = window_alerts[window_alerts['alert_type'] == 'Insufficient accumulator data']
        insufficient_base_alerts = window_alerts[window_alerts['alert_type'] == 'Insufficient baseline data']

        # Exclude fall if the system was analytically blinded due to missing data during the prodrome
        if valid_alerts.empty and (not insufficient_acc_alerts.empty or not insufficient_base_alerts.empty):
            processed.loc[idx, 'excluded_from_recall'] = True
            continue 
            
        valid_fall_count += 1
        
        # Proactive Evaluation Window (Δt) Calculation (using last valid identified state transition within max_window)
        if not valid_alerts.empty:
            last_alert_date = valid_alerts['date'].max()
            lead_time_days = (fd - last_alert_date).days
            processed.loc[idx, 'lead_time'] = lead_time_days
            
            # The identified state transition must have Δt <= 14 days to count toward sensitivity
            if lead_time_days <= max_window:
                caught_count += 1

    recall = caught_count / valid_fall_count if valid_fall_count > 0 else 0.0
    
    caught_falls_mask = (processed['Target'] == 1) & (processed['excluded_from_recall'] == False) & (processed['lead_time'] <= max_window)
    median_lead_time = processed.loc[caught_falls_mask, 'lead_time'].median() if caught_count > 0 else 0.0
    
    # --- SPECIFICITY AND FALSE POSITIVE RATE (FPR) CALCULATION ---
    eval_data = processed[processed['date'] >= eval_start]
    fp_count = 0
    tn_count = 0
    
    for m_id, group in eval_data.groupby('monitor_id'):
        m_falls = falls[falls['monitor_id'] == m_id]['date'].values
        
        for _, row in group.iterrows():
            # Ignore day for FPR/TNR if ANY insufficient data condition triggered
            if row['alert_type'] in ['Insufficient baseline data', 'Insufficient accumulator data']:
                continue

            d = row['date']
            
            # Epidemiological Censoring: Exclude the 14-day pre-fall prodromal lookback windows
            # to prevent penalising accurate ante-hoc early warnings as operational false positives
            has_fall_in_window = False
            for f_date in m_falls:
                if d <= f_date <= d + pd.Timedelta(days=max_window):
                    has_fall_in_window = True
                    break
            
            is_cond_neg = not has_fall_in_window
            
            # Check if trajectory departed into Acute Departure or Cumulative Drift
            is_alert = row['alert_type'] in ['Red Flag', 'Accumulator']
            
            if is_cond_neg:
                if is_alert:
                    fp_count += 1
                else:
                    tn_count += 1
                    
    total_negatives = fp_count + tn_count
    fpr = fp_count / total_negatives if total_negatives > 0 else 0.0
    specificity = 1.0 - fpr
    
    print(f"\n--- ALGORITHMIC PERFORMANCE SUMMARY ---")
    print(f"Total Recorded Telemetric Fall Incidents: {len(falls)}")
    print(f"Pre-Analytical Exclusions (Baseline Sufficiency 14/14 Rule): {len(falls) - valid_fall_count}")
    print(f"Protocol-Valid Falls with Captured Trajectory Drift: {caught_count}")
    print(f"Uncoupled (Non-Fall) Trajectory Departures: {fp_count}")
    print(f"Quiescent Baseline Resting Intervals (True Negatives): {tn_count}")
    print(f"---------------------------------------")
    print(f"Benchmark Sensitivity: {recall:.1%}")
    print(f"Nocturnal Specificity (from {eval_start.date()}): {specificity:.2%} (Uncoupled Departure Rate: {fpr:.2%})")

    if caught_count > 0:
        print(f"Median Proactive Evaluation Window (\u0394t) for Captured Falls: {median_lead_time:.1f} days")

    return processed

if __name__ == "__main__":

    validation_file = 'data/validation_set.csv'
    df_predictions = pd.read_csv(validation_file, parse_dates=['date'])

    eval_start_date = pd.to_datetime('2025-12-01')

    df_final = execute_post_pred(df_predictions, eval_start_date)